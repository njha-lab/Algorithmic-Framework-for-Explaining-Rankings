"""
converter.py

Utility functions for converting CSV datasets
to RankSVM format.

Supports

1. Full ranking
2. Top-k ranking
3. Existing relevance labels

Also validates feature columns and removes
malformed rows automatically.
"""

import pandas as pd


# =======================================================
# Utility Functions
# =======================================================

def remove_unnamed_columns(df):
    """
    Removes columns automatically generated by pandas.

    Example

    Unnamed: 0
    """

    return df.loc[:, ~df.columns.str.contains("^Unnamed")]


# =======================================================
# Data Validation
# =======================================================

def validate_features(df, feature_columns):
    """
    Ensures all feature columns exist
    and contain only numeric values.

    Malformed rows are removed.
    """

    print("\nValidating feature columns...\n")

    # ---------- check column names ----------

    for feature in feature_columns:

        if feature not in df.columns:

            raise ValueError(

                f"\nFeature '{feature}' not found.\n"

                f"Available columns:\n"

                f"{list(df.columns)}"

            )

    # ---------- convert to numeric ----------

    removed = 0

    for feature in feature_columns:

        numeric = pd.to_numeric(

            df[feature],

            errors="coerce"

        )

        bad = numeric.isna()

        if bad.any():

            print(

                f"Found {bad.sum()} malformed rows in "

                f"feature '{feature}'."

            )

            print(df.loc[bad].head())

            removed += bad.sum()

            df = df.loc[~bad].copy()

    # ---------- convert ----------

    for feature in feature_columns:

        df[feature] = pd.to_numeric(df[feature])

    if removed:

        print(

            f"\nRemoved {removed} malformed rows."

        )

    else:

        print("All feature columns are valid.")

    return df


# =======================================================
# Full Ranking
# =======================================================

def assign_relevance_full(

        df,

        ranking_column,

        higher_is_better,

):
    """
    Full ranking.

    Automatically preserves ties.
    """

    ascending = not higher_is_better

    df = df.sort_values(

        ranking_column,

        ascending=ascending,

    ).reset_index(drop=True)

    values = df[ranking_column].tolist()

    relevance = []

    current = len(df)

    relevance.append(current)

    for i in range(1, len(df)):

        if values[i] == values[i - 1]:

            relevance.append(

                relevance[-1]

            )

        else:

            current -= 1

            relevance.append(current)

    df["relevance"] = relevance

    return df


# =======================================================
# Existing relevance labels
# =======================================================

def assign_relevance_existing(

        df,

        relevance_column,

):
    """
    Compress relevance labels.

    Example

    10 10 8 8 3

    becomes

    3 3 2 2 1
    """

    unique = sorted(

        df[relevance_column].unique(),

        reverse=True

    )

    mapping = {}

    current = len(unique)

    for x in unique:

        mapping[x] = current

        current -= 1

    df["relevance"] = (

        df[relevance_column]

        .map(mapping)

    )

    return df


# =======================================================
# Top-k
# =======================================================

def assign_relevance_topk(

        df,

        ranking_column,

        higher_is_better,

        k,

):
    """
    Top-k ranking.

    Only the order inside the top-k
    is known.

    Everything after k receives
    relevance zero.
    """

    ascending = not higher_is_better

    df = df.sort_values(

        ranking_column,

        ascending=ascending,

    ).reset_index(drop=True)

    n = len(df)

    if k > n:

        k = n

    relevance = [0] * n

    current = k

    relevance[0] = current

    for i in range(1, k):

        if (

            df.loc[i, ranking_column]

            ==

            df.loc[i - 1, ranking_column]

        ):

            relevance[i] = relevance[i - 1]

        else:

            current -= 1

            relevance[i] = current

    df["relevance"] = relevance

    return df


# =======================================================
# Write RankSVM file
# =======================================================

def convert_to_svmrank(

        df,

        output_file,

        feature_columns,

        qid=1,

):
    """
    Converts dataframe to RankSVM format.
    """

    with open(output_file, "w") as f:

        for _, row in df.iterrows():

            line = f"{int(row['relevance'])} qid:{qid}"

            for i, feature in enumerate(

                    feature_columns,

                    start=1,

            ):

                value = row[feature]

                line += f" {i}:{value}"

            f.write(line + "\n")

    print("\nCreated")

    print(output_file)


